def poblar_obras_semilla() -> int:
    session = SessionLocal()
    engine = session.get_bind()
    with engine.begin() as conn:
        # Limpiar obras de la ejecutora
        conn.execute(
            text("DELETE FROM siaf.inversiones WHERE sec_ejec = :sec_ejec"),
            {"sec_ejec": settings.SEC_EJEC},
        )
        cols = ", ".join(_COLUMNAS)
        binds = ", ".join(f":{c}" for c in _COLUMNAS)
        stmt = text(f"INSERT INTO siaf.inversiones ({cols}) VALUES ({binds})")
        filas_norm = [{k: fila.get(k) for k in _COLUMNAS} for fila in OBRAS_SAN_JERONIMO]
        conn.execute(stmt, filas_norm)

        # Registrar en logs.sincronizacion como exito provisional
        conn.execute(
            text(
                """
                INSERT INTO logs.sincronizacion (job, estado, inicio, fin, registros_procesados)
                VALUES ('invierte', 'exito', now(), now(), :n)
                """
            ),
            {"n": len(filas_norm)},
        )

    session.close()
    logger.info("Pobladas %d obras de San Jerónimo con éxito.", len(OBRAS_SAN_JERONIMO))
    return len(OBRAS_SAN_JERONIMO)


