	FROM TMP_SEGUIMIENTO_PAAC_MODIF
	WHERE 
	CREPORTE = @PN_REPORTE AND
	CANO_EJE = @CANO_EJE AND
	CSEC_EJEC = @CSEC_EJEC AND
	CTIPO_CONSOLID = @CTIPO_CONSOLID AND
	CNRO_CONSOLID = @CNRO_CONSOLID AND
	CTIPO_GENERACION = @CTIPO_GENERACION AND
	SESTADO = 'BUENAPRO CONSENTIDA'AND
	SADJUDICADO = 'S'

	IF @WCUENTA_TOTAL_ITEM_BUENA_PRO_CON_S IS NULL
	BEGIN
		SELECT @WCUENTA_TOTAL_ITEM_BUENA_PRO_CON_S = 0 
	END

	IF @WCUENTA_TOTAL_ITEM > 0 AND @WCUENTA_TOTAL_ITEM_BUENA_PRO_CON_S > 0
	BEGIN
		SELECT @CTITULO = 'CONCLUIDO'
	END


	SELECT @WCUENTA_TOTAL_ITEM_BUENA_PRO_CON_N = COUNT(*)
	FROM TMP_SEGUIMIENTO_PAAC_MODIF
	WHERE 
	CREPORTE = @PN_REPORTE AND
	CANO_EJE = @CANO_EJE AND
	CSEC_EJEC = @CSEC_EJEC AND
	CTIPO_CONSOLID = @CTIPO_CONSOLID AND
	CNRO_CONSOLID = @CNRO_CONSOLID AND
	CTIPO_GENERACION = @CTIPO_GENERACION AND
	SESTADO = 'BUENAPRO CONSENTIDA'AND
	SADJUDICADO = 'N'

	IF @WCUENTA_TOTAL_ITEM_BUENA_PRO_CON_N IS NULL
	BEGIN
		SELECT @WCUENTA_TOTAL_ITEM_BUENA_PRO_CON_N = 0 
	END

	IF @WCUENTA_TOTAL_ITEM > 0 AND @WCUENTA_TOTAL_ITEM_BUENA_PRO_CON_N > 0
	BEGIN
		SELECT @CTITULO = 'PROCESO'
	END

	UPDATE TMP_SEGUIMIENTO_PAAC_MODIF
	SET CTITULO = @CTITULO
	WHERE
	CREPORTE = @PN_REPORTE AND
	CANO_EJE = @CANO_EJE AND
	CSEC_EJEC = @CSEC_EJEC AND
	CTIPO_CONSOLID = @CTIPO_CONSOLID AND
	CNRO_CONSOLID = @CNRO_CONSOLID AND
	CTIPO_GENERACION = @CTIPO_GENERACION 

