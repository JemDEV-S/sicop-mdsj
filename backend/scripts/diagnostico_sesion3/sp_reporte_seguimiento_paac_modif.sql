	--ASIGNAR DESCRIPCION DE ESTADO EN CABECERA

	FETCH CUR_PAAC INTO @CANO_EJE,@CSEC_EJEC,@CTIPO_CONSOLID,@CNRO_CONSOLID,
	@CTIPO_GENERACION,@CFLAG_PAAC,@CNRO_PAAC,@CITEM_UNICO ,@CTIPO_PROCESO,
	@CNOM_TIPO_PROCESO,@CNOM_TIPO_PROCESO_ABREV, @COBJETO,@CNOM_OBJETO,@CESPEC_TECNICAS,
	@ESIGLAS,@ESECTOR,@EPLIEGO,@PNOM_PLIEGO ,@ENOM_EJECUTORA,
	@ERUC_EJEC,@CINSTRUMENTO, @CVALOR_MONEDA

END

